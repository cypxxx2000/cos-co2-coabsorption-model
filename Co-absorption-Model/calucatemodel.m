%% Batch solve from Excel -> write results to text/csv
% STATIC ABSORPTION VESSEL (closed system), equilibrium only
% Chemistry:
%   (1) Adducts (1st step only):
%       A + CO2(aq) <-> ACOOH      with  [ACOOH] = KCO2 * [A] * [CO2(aq)]
%       A + COS(aq) <-> ACOSH      with  [ACOSH] = KCOS * [A] * [COS(aq)]
%   (2) COS hydrolysis overall (as provided):
%       A + H2O + COS <-> AH+ + HS- + CO2
%       Khyd = ([AH+][HS-] * c) / (a * s), and take [AH+] = [HS-] = x
%       => x = sqrt( Khyd * a * s / c )
%
% Unknowns: u1 (nCO2_g, mol), u2 (nCOS_g, mol), a ([A] free amine, mol/L)
% Equations:
%   (1) Amine balance: a + ACOOH + ACOSH + x = CA0
%   (2) CO2 balance  : u1 + VL*(c + ACOOH) = nCO2_0 + VL*x
%   (3) COS balance  : u2 + VL*(s + ACOSH + x) = nCOS_0
%
% Henry form (H in bar):
%   P = u*R*T/Vg  (bar if R,Vg consistent)
%   c = CLtot*P/H (mol/L)

clear; clc;

%% ========= Choose Excel file =========
[file, path] = uigetfile({'*.xlsx;*.xls','Excel Files (*.xlsx, *.xls)'}, 'Select parameter Excel file');
if isequal(file,0)
    error('No Excel file selected.');
end
excelFile = fullfile(path, file);

sheetName  = 1;
resultTxt  = fullfile(path, 'results_static_adduct_plus_hydrolysis.txt');
resultCsv  = fullfile(path, 'results_static_adduct_plus_hydrolysis.csv');

maxTries   = 400;
tolRes     = 1e-10;

opts = optimoptions('fsolve', ...
    'Display','off', ...
    'FunctionTolerance',1e-14, ...
    'StepTolerance',1e-14, ...
    'OptimalityTolerance',1e-14, ...
    'MaxIterations',2500, ...
    'MaxFunctionEvaluations',40000);

rng('shuffle');

%% ========= Read Excel =========
Ttbl = readtable(excelFile, 'Sheet', sheetName, 'PreserveVariableNames', true);

% ---- Required numeric parameter columns ----
reqNum = {'R','T','Vg','VL','CLtot','CA0','ng0','yCOS0','yCO20','HCOS','HCO2','KCO2','KCOS','Khyd'};
missingNum = setdiff(reqNum, Ttbl.Properties.VariableNames);
if ~isempty(missingNum)
    error('Excel缺少这些数值列名：%s', strjoin(missingNum, ', '));
end

% ---- Optional columns: Solvent + MassConc (support aliases, incl. Chinese) ----
solventCol = resolve_col(Ttbl.Properties.VariableNames, {'Solvent','solvent','溶剂分子','溶剂'});
massCol    = resolve_col(Ttbl.Properties.VariableNames, {'MassConc','massconc','mass_conc','质量浓度','浓度'});

nCase = height(Ttbl);
fprintf('Excel: %s\nTotal cases: %d\n', excelFile, nCase);

%% ========= Prepare output arrays =========
CaseID   = (1:nCase).';

Solvent  = strings(nCase,1);
MassConc = nan(nCase,1);
TempK    = nan(nCase,1);

Solved   = false(nCase,1);
Tries    = nan(nCase,1);
Exitflag = nan(nCase,1);

% Unknowns (solution)
u1 = nan(nCase,1);   % mol, nCO2_g
u2 = nan(nCase,1);   % mol, nCOS_g
a  = nan(nCase,1);   % mol/L, free amine

% Gas-phase pressures (bar)
PCO2 = nan(nCase,1);
PCOS = nan(nCase,1);
Ptot = nan(nCase,1);

% Liquid concentrations (mol/L)
cCO2  = nan(nCase,1);  % free CO2(aq)
cCOS  = nan(nCase,1);  % free COS(aq)
ACOOH = nan(nCase,1);
ACOSH = nan(nCase,1);

AH    = nan(nCase,1);  % [AH+] from hydrolysis (mol/L)
HS    = nan(nCase,1);  % [HS-] from hydrolysis (mol/L)

% Mole accounting (mol)
nCO2_0 = nan(nCase,1);
nCOS_0 = nan(nCase,1);

nCO2_gen = nan(nCase,1); % VL*x (mol) CO2 generated by hydrolysis
nCOS_hyd = nan(nCase,1); % VL*x (mol) COS consumed by hydrolysis

nCO2_abs_net = nan(nCase,1); % nCO2_0 - u1 (can be negative if CO2 increases in gas)
nCOS_abs     = nan(nCase,1); % nCOS_0 - u2 (>=0)

ResNormScaled = nan(nCase,1);
ResNormRaw    = nan(nCase,1);

%% ========= Loop over cases =========
for i = 1:nCase
    if ~isempty(solventCol)
        Solvent(i)  = to_string(Ttbl.(solventCol)(i));
    else
        Solvent(i) = "";
    end
    if ~isempty(massCol)
        MassConc(i) = to_double(Ttbl.(massCol)(i));
    else
        MassConc(i) = NaN;
    end
    TempK(i) = to_double(Ttbl.('T')(i));

    % Build parameter struct p for this row
    p = struct();
    for kf = 1:numel(reqNum)
        key = reqNum{kf};
        p.(key) = to_double(Ttbl.(key)(i));
    end
    p.Solvent  = Solvent(i);
    p.MassConc = MassConc(i);

    [solved, out, stats] = solve_one_case_static_3eq_hyd(p, maxTries, tolRes, opts);

    Solved(i)   = solved;
    Tries(i)    = stats.triesUsed;
    Exitflag(i) = stats.exitflag;
    ResNormScaled(i) = stats.bestScaledNorm;
    ResNormRaw(i)    = stats.bestRawNorm;

    % record initial moles (for reporting)
    nCO2_0(i) = max(0, p.ng0*p.yCO20);
    nCOS_0(i) = max(0, p.ng0*p.yCOS0);

    if solved
        u1(i) = out.u1; u2(i) = out.u2; a(i) = out.a;

        PCO2(i) = out.PCO2; PCOS(i) = out.PCOS; Ptot(i) = out.Ptot;

        cCO2(i) = out.cCO2; cCOS(i) = out.cCOS;
        ACOOH(i) = out.ACOOH; ACOSH(i) = out.ACOSH;

        AH(i) = out.AH; HS(i) = out.HS;

        nCO2_gen(i) = out.nCO2_gen;
        nCOS_hyd(i) = out.nCOS_hyd;

        nCO2_abs_net(i) = out.nCO2_abs_net;
        nCOS_abs(i)     = out.nCOS_abs;
    end

    fprintf(['Case %d/%d: solvent=%s, massConc=%.6g, T=%.4g K, solved=%d, tries=%d, bestScaled=%.3e, ' ...
             'u1=%.3e mol, u2=%.3e mol, a=%.3e mol/L, PCO2=%.3e bar, PCOS=%.3e bar, x(AH/HS)=%.3e mol/L\n'], ...
        i, nCase, Solvent(i), MassConc(i), TempK(i), solved, stats.triesUsed, stats.bestScaledNorm, ...
        out.u1, out.u2, out.a, out.PCO2, out.PCOS, out.AH);
end

%% ========= Write results =========
Rout = table( ...
    CaseID, Solvent, MassConc, TempK, Solved, Tries, Exitflag, ...
    nCO2_0, nCOS_0, ...
    u1, u2, a, PCO2, PCOS, Ptot, ...
    cCO2, cCOS, ACOOH, ACOSH, AH, HS, ...
    nCO2_gen, nCOS_hyd, nCO2_abs_net, nCOS_abs, ...
    ResNormScaled, ResNormRaw);

Rout.Properties.VariableNames{'TempK'} = 'Temperature_K';

writetable(Rout, resultTxt, 'Delimiter','\t');
writetable(Rout, resultCsv);

fprintf('\nDone. Results written to:\n  %s\n  %s\n', resultTxt, resultCsv);

%% ================= Local functions =================

function col = resolve_col(varNames, aliases)
    col = '';
    lowerNames = lower(string(varNames));
    for k = 1:numel(aliases)
        target = lower(string(aliases{k}));
        idx = find(lowerNames == target, 1);
        if ~isempty(idx)
            col = varNames{idx};
            return;
        end
    end
end

function s = to_string(v)
    if isstring(v)
        s = v;
    elseif ischar(v)
        s = string(v);
    elseif iscell(v)
        if isempty(v)
            s = "";
        else
            s = string(v{1});
        end
    else
        s = string(v);
    end
    if strlength(s) == 0
        s = "";
    end
end

function x = to_double(v)
    if isnumeric(v)
        x = v;
        return;
    end
    if iscell(v)
        if isempty(v)
            x = NaN;
            return;
        end
        v = v{1};
    end
    if isstring(v) || ischar(v)
        x = str2double(v);
    else
        x = double(v);
    end
end

%% ========= Solver: 3 unknowns (u1,u2,a), 3 equations (A, CO2, COS) =========
function [solved, out, stats] = solve_one_case_static_3eq_hyd(p, maxTries, tolRes, opts)

    solved = false;

    out = struct('u1',NaN,'u2',NaN,'a',NaN, ...
                 'PCO2',NaN,'PCOS',NaN,'Ptot',NaN, ...
                 'cCO2',NaN,'cCOS',NaN,'ACOOH',NaN,'ACOSH',NaN, ...
                 'AH',NaN,'HS',NaN, ...
                 'nCO2_gen',NaN,'nCOS_hyd',NaN, ...
                 'nCO2_abs_net',NaN,'nCOS_abs',NaN);

    best = struct('scaledNorm',inf,'rawNorm',inf,'exitflag',-999,'out',out);

    % Quick checks
    if any(~isfinite([p.R,p.T,p.Vg,p.VL,p.CLtot,p.CA0,p.ng0,p.yCO20,p.yCOS0,p.HCO2,p.HCOS,p.KCO2,p.KCOS,p.Khyd])) || ...
       p.R<=0 || p.T<=0 || p.Vg<=0 || p.VL<0 || p.CLtot<=0 || p.CA0<0 || p.ng0<0 || p.HCO2<=0 || p.HCOS<=0 || p.Khyd<0
        stats.triesUsed = 0;
        stats.exitflag = -999;
        stats.bestScaledNorm = inf;
        stats.bestRawNorm = inf;
        return;
    end

    nCO2_0 = max(0, p.ng0 * p.yCO20);
    nCOS_0 = max(0, p.ng0 * p.yCOS0);
    nInert_0 = max(0, p.ng0 * max(0, 1 - p.yCO20 - p.yCOS0)); % for Ptot only

    % Trivial case: no reactive gas
    if nCO2_0==0 && nCOS_0==0
        out.u1 = 0; out.u2 = 0; out.a = p.CA0;
        out.PCO2 = 0; out.PCOS = 0;
        out.Ptot = nInert_0 * p.R * p.T / p.Vg;
        out.cCO2 = 0; out.cCOS = 0;
        out.ACOOH = 0; out.ACOSH = 0;
        out.AH = 0; out.HS = 0;
        out.nCO2_gen = 0; out.nCOS_hyd = 0;
        out.nCO2_abs_net = 0; out.nCOS_abs = 0;

        solved = true;
        stats.triesUsed = 1;
        stats.exitflag = 1;
        stats.bestScaledNorm = 0;
        stats.bestRawNorm = 0;
        return;
    end

    % Use log-variables to enforce positivity
    % z = log([u1,u2,a])
    uMin = 1e-30;  % mol
    aMin = 1e-30;  % mol/L

    for k = 1:maxTries
        z0 = makeInitialGuess_log_uua(nCO2_0, nCOS_0, p.CA0, uMin, aMin);

        G = @(z) residual3_scaled_from_z(z, p, nCO2_0, nCOS_0, uMin, aMin);

        try
            [zsol, fval, exitflag] = fsolve(G, z0, opts);
        catch
            continue;
        end

        if exitflag <= 0 || any(~isfinite(zsol)) || any(~isfinite(fval))
            continue;
        end

        scaledNorm = norm(fval,2);

        x = exp(zsol(:));
        x(1) = max(uMin, x(1));
        x(2) = max(uMin, x(2));
        x(3) = max(aMin, x(3));

        raw = residual3_raw_from_x(x, p, nCO2_0, nCOS_0);
        rawNorm = norm(raw,2);

        out_try = compute_outputs_from_x(x, p, nCO2_0, nCOS_0, nInert_0);

        if scaledNorm < best.scaledNorm
            best.scaledNorm = scaledNorm;
            best.rawNorm = rawNorm;
            best.exitflag = exitflag;
            best.out = out_try;
        end

        if scaledNorm < tolRes
            solved = true;
            break;
        end
    end

    out = best.out;

    stats.triesUsed = min(maxTries, k);
    stats.exitflag = best.exitflag;
    stats.bestScaledNorm = best.scaledNorm;
    stats.bestRawNorm = best.rawNorm;
end

function z0 = makeInitialGuess_log_uua(nCO2_0, nCOS_0, CA0, uMin, aMin)
    if nCO2_0 > 0
        u1 = max(uMin, nCO2_0 * 10^(-6 + 6*rand));
    else
        u1 = uMin * 10^(0 + 6*rand);
    end

    if nCOS_0 > 0
        u2 = max(uMin, nCOS_0 * 10^(-6 + 6*rand));
    else
        u2 = uMin * 10^(0 + 6*rand);
    end

    if CA0 > 0
        a = max(aMin, CA0 * 10^(-6 + 6*rand));
    else
        a = aMin * 10^(0 + 6*rand);
    end

    z0 = log([u1; u2; a]);
end

%% ========= Scaled residuals =========
function r = residual3_scaled_from_z(z, p, nCO2_0, nCOS_0, uMin, aMin)
    x = exp(z(:));
    x(1) = max(uMin, x(1));
    x(2) = max(uMin, x(2));
    x(3) = max(aMin, x(3));

    rraw = residual3_raw_from_x(x, p, nCO2_0, nCOS_0);

    if any(~isfinite(rraw))
        r = ones(3,1)*1e6;
        return;
    end

    % scales: amine in mol/L, gas balances in mol
    scaleA   = max(1, p.CA0);
    scaleCO2 = max(1, nCO2_0 + p.VL*p.CA0);
    scaleCOS = max(1, nCOS_0 + p.VL*p.CA0);

    r = rraw ./ [scaleA; scaleCO2; scaleCOS];

    if any(~isfinite(r))
        r = ones(3,1)*1e6;
    end
end

%% ========= Raw residuals: [amine, CO2, COS] =========
function rraw = residual3_raw_from_x(x, p, nCO2_0, nCOS_0)
    u1 = x(1); u2 = x(2); a = x(3);

    % pressures (bar)
    PCO2 = u1 * p.R * p.T / p.Vg;
    PCOS = u2 * p.R * p.T / p.Vg;

    if any(~isfinite([PCO2,PCOS])) || PCO2<0 || PCOS<0
        rraw = ones(3,1)*1e30;
        return;
    end

    % Henry: c = CLtot * P / H  (mol/L)
    c = p.CLtot * PCO2 / p.HCO2;
    s = p.CLtot * PCOS / p.HCOS;

    if any(~isfinite([c,s])) || any([c,s] < 0)
        rraw = ones(3,1)*1e30;
        return;
    end

    % Adducts (mol/L)
    ACOOH = p.KCO2 * a * c;
    ACOSH = p.KCOS * a * s;

    if any(~isfinite([ACOOH,ACOSH])) || any([ACOOH,ACOSH] < 0)
        rraw = ones(3,1)*1e30;
        return;
    end

    % Hydrolysis ionic pair: x = [AH+] = [HS-]
    % x^2 = Khyd * a * s / c
    epsC = 1e-30;
    if p.Khyd == 0
        xion = 0;
    else
        val = p.Khyd * a * s / max(c, epsC);
        if ~isfinite(val) || val < 0
            rraw = ones(3,1)*1e30;
            return;
        end
        xion = sqrt(val);
    end

    if ~isfinite(xion) || xion < 0
        rraw = ones(3,1)*1e30;
        return;
    end

    rraw = zeros(3,1);

    % (1) amine balance (mol/L)
    rraw(1) = a + ACOOH + ACOSH + xion - p.CA0;

    % (2) CO2 balance (mol): include generation by hydrolysis (+VL*xion)
    rraw(2) = u1 + p.VL*(c + ACOOH) - (nCO2_0 + p.VL*xion);

    % (3) COS balance (mol): include consumption by hydrolysis (+VL*xion in liquid inventory)
    rraw(3) = u2 + p.VL*(s + ACOSH + xion) - nCOS_0;
end

function out = compute_outputs_from_x(x, p, nCO2_0, nCOS_0, nInert_0)
    u1 = x(1); u2 = x(2); a = x(3);

    PCO2 = u1 * p.R * p.T / p.Vg;
    PCOS = u2 * p.R * p.T / p.Vg;

    c = p.CLtot * PCO2 / p.HCO2;
    s = p.CLtot * PCOS / p.HCOS;

    ACOOH = p.KCO2 * a * c;
    ACOSH = p.KCOS * a * s;

    epsC = 1e-30;
    if p.Khyd == 0
        xion = 0;
    else
        xion = sqrt(max(0, p.Khyd * a * s / max(c, epsC)));
    end

    out.u1 = u1; out.u2 = u2; out.a = a;
    out.PCO2 = PCO2; out.PCOS = PCOS;

    ntot_g = nInert_0 + u1 + u2;
    out.Ptot = ntot_g * p.R * p.T / p.Vg;

    out.cCO2 = c; out.cCOS = s;
    out.ACOOH = ACOOH; out.ACOSH = ACOSH;

    out.AH = xion;
    out.HS = xion;

    out.nCO2_gen = p.VL * xion;  % mol CO2 generated by hydrolysis
    out.nCOS_hyd = p.VL * xion;  % mol COS consumed by hydrolysis

    out.nCO2_abs_net = nCO2_0 - u1; % can be negative if CO2 in gas increases
    out.nCOS_abs     = nCOS_0 - u2; % >=0 expected
end
