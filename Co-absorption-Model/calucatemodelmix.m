%% Batch solve from Excel -> write results to text/csv
% STATIC ABSORPTION VESSEL (closed system), equilibrium only
% Chemistry (MIXED AMINES A + B):
%   (1) Adducts (1st step only):
%       A + CO2(aq) <-> ACOOH      [ACOOH] = KCO2A * a * c
%       A + COS(aq) <-> ACOSH      [ACOSH] = KCOSA * a * s
%       B + CO2(aq) <-> BCOOH      [BCOOH] = KCO2B * b * c
%       B + COS(aq) <-> BCOSH      [BCOSH] = KCOSB * b * s
%   (2) COS hydrolysis overall (amine-catalyzed, BOTH amines):
%       A + H2O + COS <-> AH+ + HS- + CO2     KhydA = ([AH+][HS-] * c) / (a * s)
%       B + H2O + COS <-> BH+ + HS- + CO2     KhydB = ([BH+][HS-] * c) / (b * s)
%       Closure (same as your previous method): [HS-]=x, and [AH+]+[BH+]=x
%       => x^2 = (s/c) * (KhydA*a + KhydB*b)
%          AH = KhydA*a*s/(c*x),  BH = KhydB*b*s/(c*x)
%
% Unknowns: u1 (nCO2_g, mol), u2 (nCOS_g, mol), a ([A] free, mol/L), b ([B] free, mol/L)
% Equations:
%   (1) A balance : a + ACOOH + ACOSH + AH = CA0
%   (2) B balance : b + BCOOH + BCOSH + BH = CB0
%   (3) CO2 balance: u1 + VL*(c + ACOOH + BCOOH) = nCO2_0 + VL*x
%   (4) COS balance: u2 + VL*(s + ACOSH + BCOSH + x) = nCOS_0
%
% Henry form (H in bar):
%   P = u*R*T/Vg  (bar if R,Vg consistent)
%   c = CLtot*P/H (mol/L)

clear; clc;

%% ========= Choose Excel file =========
[file, path] = uigetfile({'*.xlsx;*.xls','Excel Files (*.xlsx, *.xls)'}, 'Select parameter Excel file');
if isequal(file,0)
    error('No Excel file selected.');
end
excelFile = fullfile(path, file);

sheetName  = 1;
resultTxt  = fullfile(path, 'results_static_mixAB_adduct_plus_hydrolysis.txt');
resultCsv  = fullfile(path, 'results_static_mixAB_adduct_plus_hydrolysis.csv');

maxTries   = 600;
tolRes     = 1e-10;

opts = optimoptions('fsolve', ...
    'Display','off', ...
    'FunctionTolerance',1e-14, ...
    'StepTolerance',1e-14, ...
    'OptimalityTolerance',1e-14, ...
    'MaxIterations',3000, ...
    'MaxFunctionEvaluations',80000);

rng('shuffle');

%% ========= Read Excel =========
Ttbl = readtable(excelFile, 'Sheet', sheetName, 'PreserveVariableNames', true);
varNames = Ttbl.Properties.VariableNames;

% ---- Optional columns: Solvent + MassConc (support aliases, incl. Chinese) ----
solventCol = resolve_col(varNames, {'Solvent','solvent','溶剂分子','溶剂'});
massCol    = resolve_col(varNames, {'MassConc','massconc','mass_conc','质量浓度','浓度'});

% ---- Required numeric columns with aliases (more robust than fixed reqNum) ----
need = struct();
need.R     = {'R'};
need.T     = {'T'};
need.Vg    = {'Vg','VG','V_g'};
need.VL    = {'VL','Vl','V_L'};
need.CLtot = {'CLtot','CLTot','C_Ltot','CL_total'};
need.ng0   = {'ng0','n_g0'};
need.yCO20 = {'yCO20','yCO2_0','yCO2'};
need.yCOS0 = {'yCOS0','yCOS_0','yCOS'};
need.HCO2  = {'HCO2','H_CO2','HenryCO2'};
need.HCOS  = {'HCOS','H_COS','HenryCOS'};

need.CA0   = {'CA0','C_A0','CA_0'};
need.CB0   = {'CB0','C_B0','CB_0'};

% A constants: allow legacy names without suffix
need.KCO2A = {'KCO2A','KCO2_A','KCO2'};
need.KCOSA = {'KCOSA','KCOS_A','KCOS'};
need.KhydA = {'KhydA','Khyd_A','Khyd'};

% B constants: must be present for mixed amine
need.KCO2B = {'KCO2B','KCO2_B'};
need.KCOSB = {'KCOSB','KCOS_B'};
need.KhydB = {'KhydB','Khyd_B'};

colMap = struct();
fns = fieldnames(need);
missing = strings(0);
for k = 1:numel(fns)
    fn = fns{k};
    col = resolve_col(varNames, need.(fn));
    if isempty(col)
        missing(end+1) = fn; %#ok<AGROW>
    else
        colMap.(fn) = col;
    end
end
if ~isempty(missing)
    error('Excel缺少这些必要列（按内部字段名显示）：%s', strjoin(missing, ', '));
end

nCase = height(Ttbl);
fprintf('Excel: %s\nTotal cases: %d\n', excelFile, nCase);

%% ========= Prepare output arrays =========
CaseID   = (1:nCase).';

Solvent  = strings(nCase,1);
MassConc = nan(nCase,1);
TempK    = nan(nCase,1);

Solved   = false(nCase,1);
Tries    = nan(nCase,1);
Exitflag = nan(nCase,1);

% Unknowns (solution)
u1 = nan(nCase,1);   % mol, nCO2_g
u2 = nan(nCase,1);   % mol, nCOS_g
a  = nan(nCase,1);   % mol/L, free A
b  = nan(nCase,1);   % mol/L, free B

% Gas-phase pressures (bar)
PCO2 = nan(nCase,1);
PCOS = nan(nCase,1);
Ptot = nan(nCase,1);

% Liquid concentrations (mol/L)
cCO2  = nan(nCase,1);  % free CO2(aq)
cCOS  = nan(nCase,1);  % free COS(aq)

ACOOH = nan(nCase,1);
ACOSH = nan(nCase,1);
BCOOH = nan(nCase,1);
BCOSH = nan(nCase,1);

AH    = nan(nCase,1);  % [AH+]
BH    = nan(nCase,1);  % [BH+]
HS    = nan(nCase,1);  % [HS-] (= x)

% Mole accounting (mol)
nCO2_0 = nan(nCase,1);
nCOS_0 = nan(nCase,1);

nCO2_gen = nan(nCase,1); % VL*x (mol) CO2 generated by hydrolysis
nCOS_hyd = nan(nCase,1); % VL*x (mol) COS consumed by hydrolysis

nCO2_abs_net = nan(nCase,1); % nCO2_0 - u1 (can be negative if CO2 increases in gas)
nCOS_abs     = nan(nCase,1); % nCOS_0 - u2

ResNormScaled = nan(nCase,1);
ResNormRaw    = nan(nCase,1);

%% ========= Loop over cases =========
for i = 1:nCase
    if ~isempty(solventCol), Solvent(i)  = to_string(Ttbl.(solventCol)(i)); else, Solvent(i) = ""; end
    if ~isempty(massCol),    MassConc(i) = to_double(Ttbl.(massCol)(i));    else, MassConc(i) = NaN; end
    TempK(i) = to_double(Ttbl.(colMap.T)(i));

    % Build parameter struct p for this row (internal names fixed)
    p = struct();
    for kf = 1:numel(fns)
        fn = fns{kf};
        p.(fn) = to_double(Ttbl.(colMap.(fn))(i));
    end
    p.Solvent  = Solvent(i);
    p.MassConc = MassConc(i);

    [solved, out, stats] = solve_one_case_static_4eq_hyd_mixAB(p, maxTries, tolRes, opts);

    Solved(i)   = solved;
    Tries(i)    = stats.triesUsed;
    Exitflag(i) = stats.exitflag;
    ResNormScaled(i) = stats.bestScaledNorm;
    ResNormRaw(i)    = stats.bestRawNorm;

    % record initial moles (for reporting)
    nCO2_0(i) = max(0, p.ng0*p.yCO20);
    nCOS_0(i) = max(0, p.ng0*p.yCOS0);

    if solved
        u1(i) = out.u1; u2(i) = out.u2; a(i) = out.a; b(i) = out.b;

        PCO2(i) = out.PCO2; PCOS(i) = out.PCOS; Ptot(i) = out.Ptot;

        cCO2(i) = out.cCO2; cCOS(i) = out.cCOS;

        ACOOH(i) = out.ACOOH; ACOSH(i) = out.ACOSH;
        BCOOH(i) = out.BCOOH; BCOSH(i) = out.BCOSH;

        AH(i) = out.AH; BH(i) = out.BH; HS(i) = out.HS;

        nCO2_gen(i) = out.nCO2_gen;
        nCOS_hyd(i) = out.nCOS_hyd;

        nCO2_abs_net(i) = out.nCO2_abs_net;
        nCOS_abs(i)     = out.nCOS_abs;
    end

    fprintf(['Case %d/%d: solvent=%s, massConc=%.6g, T=%.4g K, solved=%d, tries=%d, bestScaled=%.3e, ' ...
             'u1=%.3e mol, u2=%.3e mol, a=%.3e, b=%.3e mol/L, PCO2=%.3e bar, PCOS=%.3e bar, HS=%.3e mol/L\n'], ...
        i, nCase, Solvent(i), MassConc(i), TempK(i), solved, stats.triesUsed, stats.bestScaledNorm, ...
        out.u1, out.u2, out.a, out.b, out.PCO2, out.PCOS, out.HS);
end

%% ========= Write results =========
Rout = table( ...
    CaseID, Solvent, MassConc, TempK, Solved, Tries, Exitflag, ...
    nCO2_0, nCOS_0, ...
    u1, u2, a, b, PCO2, PCOS, Ptot, ...
    cCO2, cCOS, ...
    ACOOH, ACOSH, BCOOH, BCOSH, ...
    AH, BH, HS, ...
    nCO2_gen, nCOS_hyd, nCO2_abs_net, nCOS_abs, ...
    ResNormScaled, ResNormRaw);

Rout.Properties.VariableNames{'TempK'} = 'Temperature_K';

writetable(Rout, resultTxt, 'Delimiter','\t');
writetable(Rout, resultCsv);

fprintf('\nDone. Results written to:\n  %s\n  %s\n', resultTxt, resultCsv);

%% ================= Local functions =================

function col = resolve_col(varNames, aliases)
    col = '';
    lowerNames = lower(string(varNames));
    for k = 1:numel(aliases)
        target = lower(string(aliases{k}));
        idx = find(lowerNames == target, 1);
        if ~isempty(idx)
            col = varNames{idx};
            return;
        end
    end
end

function s = to_string(v)
    if isstring(v)
        s = v;
    elseif ischar(v)
        s = string(v);
    elseif iscell(v)
        if isempty(v), s = ""; else, s = string(v{1}); end
    else
        s = string(v);
    end
    if strlength(s) == 0, s = ""; end
end

function x = to_double(v)
    if isnumeric(v), x = v; return; end
    if iscell(v)
        if isempty(v), x = NaN; return; end
        v = v{1};
    end
    if isstring(v) || ischar(v)
        x = str2double(v);
    else
        x = double(v);
    end
end

%% ========= Solver: 4 unknowns (u1,u2,a,b), 4 equations (A, B, CO2, COS) =========
function [solved, out, stats] = solve_one_case_static_4eq_hyd_mixAB(p, maxTries, tolRes, opts)

    solved = false;

    out = struct('u1',NaN,'u2',NaN,'a',NaN,'b',NaN, ...
                 'PCO2',NaN,'PCOS',NaN,'Ptot',NaN, ...
                 'cCO2',NaN,'cCOS',NaN, ...
                 'ACOOH',NaN,'ACOSH',NaN,'BCOOH',NaN,'BCOSH',NaN, ...
                 'AH',NaN,'BH',NaN,'HS',NaN, ...
                 'nCO2_gen',NaN,'nCOS_hyd',NaN, ...
                 'nCO2_abs_net',NaN,'nCOS_abs',NaN);

    best = struct('scaledNorm',inf,'rawNorm',inf,'exitflag',-999,'out',out);

    % Quick checks
    must = [p.R,p.T,p.Vg,p.VL,p.CLtot,p.ng0,p.yCO20,p.yCOS0,p.HCO2,p.HCOS, ...
            p.CA0,p.CB0,p.KCO2A,p.KCOSA,p.KhydA,p.KCO2B,p.KCOSB,p.KhydB];
    if any(~isfinite(must)) || ...
       p.R<=0 || p.T<=0 || p.Vg<=0 || p.VL<0 || p.CLtot<=0 || p.ng0<0 || ...
       p.HCO2<=0 || p.HCOS<=0 || p.CA0<0 || p.CB0<0 || ...
       p.KhydA<0 || p.KhydB<0
        stats.triesUsed = 0;
        stats.exitflag = -999;
        stats.bestScaledNorm = inf;
        stats.bestRawNorm = inf;
        return;
    end

    nCO2_0 = max(0, p.ng0 * p.yCO20);
    nCOS_0 = max(0, p.ng0 * p.yCOS0);
    nInert_0 = max(0, p.ng0 * max(0, 1 - p.yCO20 - p.yCOS0)); % for Ptot only

    % Use log-variables to enforce positivity: z = log([u1,u2,a,b])
    uMin = 1e-30;  % mol
    cMin = 1e-30;  % mol/L

    for k = 1:maxTries
        z0 = makeInitialGuess_log_uuab(nCO2_0, nCOS_0, p.CA0, p.CB0, uMin, cMin);
        G  = @(z) residual4_scaled_from_z(z, p, nCO2_0, nCOS_0, uMin, cMin);

        try
            [zsol, fval, exitflag] = fsolve(G, z0, opts);
        catch
            continue;
        end

        if exitflag <= 0 || any(~isfinite(zsol)) || any(~isfinite(fval))
            continue;
        end

        scaledNorm = norm(fval,2);

        x = exp(zsol(:));
        x(1) = max(uMin, x(1));
        x(2) = max(uMin, x(2));
        x(3) = max(cMin, x(3));
        x(4) = max(cMin, x(4));

        raw = residual4_raw_from_x(x, p, nCO2_0, nCOS_0);
        rawNorm = norm(raw,2);

        out_try = compute_outputs_from_x(x, p, nCO2_0, nCOS_0, nInert_0);

        if scaledNorm < best.scaledNorm
            best.scaledNorm = scaledNorm;
            best.rawNorm = rawNorm;
            best.exitflag = exitflag;
            best.out = out_try;
        end

        if scaledNorm < tolRes
            solved = true;
            break;
        end
    end

    out = best.out;

    stats.triesUsed = min(maxTries, k);
    stats.exitflag = best.exitflag;
    stats.bestScaledNorm = best.scaledNorm;
    stats.bestRawNorm = best.rawNorm;
end

function z0 = makeInitialGuess_log_uuab(nCO2_0, nCOS_0, CA0, CB0, uMin, cMin)
    if nCO2_0 > 0, u1 = max(uMin, nCO2_0 * 10^(-6 + 6*rand));
    else,          u1 = uMin * 10^(0 + 6*rand);
    end

    if nCOS_0 > 0, u2 = max(uMin, nCOS_0 * 10^(-6 + 6*rand));
    else,          u2 = uMin * 10^(0 + 6*rand);
    end

    if CA0 > 0, a = max(cMin, CA0 * 10^(-6 + 6*rand));
    else,       a = cMin * 10^(0 + 6*rand);
    end

    if CB0 > 0, b = max(cMin, CB0 * 10^(-6 + 6*rand));
    else,       b = cMin * 10^(0 + 6*rand);
    end

    z0 = log([u1; u2; a; b]);
end

function r = residual4_scaled_from_z(z, p, nCO2_0, nCOS_0, uMin, cMin)
    x = exp(z(:));
    x(1) = max(uMin, x(1));
    x(2) = max(uMin, x(2));
    x(3) = max(cMin, x(3));
    x(4) = max(cMin, x(4));

    rraw = residual4_raw_from_x(x, p, nCO2_0, nCOS_0);

    if any(~isfinite(rraw))
        r = ones(4,1)*1e6;
        return;
    end

    scaleA   = max(1, p.CA0);
    scaleB   = max(1, p.CB0);
    scaleCO2 = max(1, nCO2_0 + p.VL*(p.CA0+p.CB0));
    scaleCOS = max(1, nCOS_0 + p.VL*(p.CA0+p.CB0));

    r = rraw ./ [scaleA; scaleB; scaleCO2; scaleCOS];

    if any(~isfinite(r))
        r = ones(4,1)*1e6;
    end
end

function rraw = residual4_raw_from_x(x, p, nCO2_0, nCOS_0)
    u1 = x(1); u2 = x(2); a = x(3); b = x(4);

    % pressures (bar)
    PCO2 = u1 * p.R * p.T / p.Vg;
    PCOS = u2 * p.R * p.T / p.Vg;

    if any(~isfinite([PCO2,PCOS])) || PCO2<0 || PCOS<0
        rraw = ones(4,1)*1e30;
        return;
    end

    % Henry: c = CLtot * P / H  (mol/L)
    c = p.CLtot * PCO2 / p.HCO2;
    s = p.CLtot * PCOS / p.HCOS;

    if any(~isfinite([c,s])) || any([c,s] < 0)
        rraw = ones(4,1)*1e30;
        return;
    end

    % Adducts (mol/L)
    ACOOH = p.KCO2A * a * c;
    ACOSH = p.KCOSA * a * s;
    BCOOH = p.KCO2B * b * c;
    BCOSH = p.KCOSB * b * s;

    if any(~isfinite([ACOOH,ACOSH,BCOOH,BCOSH])) || any([ACOOH,ACOSH,BCOOH,BCOSH] < 0)
        rraw = ones(4,1)*1e30;
        return;
    end

    % Hydrolysis closure:
    % x^2 = (s/c) * (KhydA*a + KhydB*b)
    epsC = 1e-30;
    term = (s / max(c, epsC)) * (p.KhydA*a + p.KhydB*b);
    if ~isfinite(term) || term < 0
        rraw = ones(4,1)*1e30;
        return;
    end
    HS = sqrt(term); % x

    if HS == 0
        AH = 0; BH = 0;
    else
        AH = (p.KhydA * a * s) / (max(c, epsC) * HS);
        BH = (p.KhydB * b * s) / (max(c, epsC) * HS);
    end

    if any(~isfinite([HS,AH,BH])) || any([HS,AH,BH] < 0)
        rraw = ones(4,1)*1e30;
        return;
    end

    rraw = zeros(4,1);

    % (1) A amine balance (mol/L)
    rraw(1) = a + ACOOH + ACOSH + AH - p.CA0;

    % (2) B amine balance (mol/L)
    rraw(2) = b + BCOOH + BCOSH + BH - p.CB0;

    % (3) CO2 balance (mol): include generation by hydrolysis (+VL*HS)
    rraw(3) = u1 + p.VL*(c + ACOOH + BCOOH) - (nCO2_0 + p.VL*HS);

    % (4) COS balance (mol): include consumption by hydrolysis (+VL*HS)
    rraw(4) = u2 + p.VL*(s + ACOSH + BCOSH + HS) - nCOS_0;
end

function out = compute_outputs_from_x(x, p, nCO2_0, nCOS_0, nInert_0)
    u1 = x(1); u2 = x(2); a = x(3); b = x(4);

    PCO2 = u1 * p.R * p.T / p.Vg;
    PCOS = u2 * p.R * p.T / p.Vg;

    c = p.CLtot * PCO2 / p.HCO2;
    s = p.CLtot * PCOS / p.HCOS;

    ACOOH = p.KCO2A * a * c;
    ACOSH = p.KCOSA * a * s;
    BCOOH = p.KCO2B * b * c;
    BCOSH = p.KCOSB * b * s;

    epsC = 1e-30;
    HS = sqrt(max(0, (s / max(c, epsC)) * (p.KhydA*a + p.KhydB*b)));

    if HS == 0
        AH = 0; BH = 0;
    else
        AH = (p.KhydA * a * s) / (max(c, epsC) * HS);
        BH = (p.KhydB * b * s) / (max(c, epsC) * HS);
    end

    out.u1 = u1; out.u2 = u2; out.a = a; out.b = b;

    out.PCO2 = PCO2; out.PCOS = PCOS;
    ntot_g = nInert_0 + u1 + u2;
    out.Ptot = ntot_g * p.R * p.T / p.Vg;

    out.cCO2 = c; out.cCOS = s;

    out.ACOOH = ACOOH; out.ACOSH = ACOSH;
    out.BCOOH = BCOOH; out.BCOSH = BCOSH;

    out.AH = AH; out.BH = BH; out.HS = HS;

    out.nCO2_gen = p.VL * HS;
    out.nCOS_hyd = p.VL * HS;

    out.nCO2_abs_net = nCO2_0 - u1;
    out.nCOS_abs     = nCOS_0 - u2;
end
